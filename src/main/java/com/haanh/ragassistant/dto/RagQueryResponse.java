package com.haanh.ragassistant.dto;

import io.swagger.v3.oas.annotations.media.Schema;
import java.util.List;

@Schema(description = "Response payload returned by the Enterprise RAG system")
public record RagQueryResponse(
    @Schema(description = "Synthesized grounded answer generated by the assistant", 
            example = "Our platform encrypts all sensitive data at rest using AES-256 and TLS 1.3 in transit.")
    String answer,

    @Schema(description = "Verified citations referencing the uploaded documents")
    List<CitationDto> citations,

    @Schema(description = "Confidence level based on context alignment: HIGH, MEDIUM, LOW", example = "HIGH")
    String confidence,

    @Schema(description = "Indicates whether the answer was served immediately from Redis Semantic Cache", example = "false")
    boolean cacheHit,

    @Schema(description = "Total query execution latency in milliseconds", example = "42")
    long executionTimeMs,

    @Schema(description = "Estimated number of LLM tokens saved by serving from cache", example = "850")
    int estimatedTokensSaved,

    @Schema(description = "Resolution source of this query result", example = "HYBRID_RAG_LLM")
    String source
) {
    public RagQueryResponse withPerformanceMetrics(boolean cacheHit, long executionTimeMs, int tokensSaved, String source) {
        return new RagQueryResponse(
            this.answer,
            this.citations,
            this.confidence,
            cacheHit,
            executionTimeMs,
            tokensSaved,
            source
        );
    }
}
